static inline uint32_t fb_pack_rgb(uint32_t rgb) {
    // Assume 0x00RRGGBB input, return same; for 24bpp we write 3 bytes.
    return rgb;
}

int fb_init_from_bootinfo(const boot_framebuffer_info_t *info) {
    if (!info || !info->present) return -1;

    // We currently support linear truecolor (type 1) with 24 or 32 bpp.
    if (info->type != 1) return -1;
    if (info->bpp != 24 && info->bpp != 32) return -1;

    // The pager maps the framebuffer starting at FB_VIRT_BASE aligned to 4 KiB.
    // Preserve the original physical offset within the first page.
    uint32_t offset = (uint32_t)(info->addr & 0xFFF);

    fb_driver.virt_addr = (uint8_t *)(FB_VIRT_BASE + offset);
    fb_driver.pitch     = info->pitch;
    fb_driver.width     = info->width;
    fb_driver.height    = info->height;
    fb_driver.bpp       = info->bpp;

    return 0;
}

void fb_clear(uint32_t rgb) {
    if (!fb_driver.virt_addr) return;

    uint32_t packed = fb_pack_rgb(rgb);
    uint32_t bytes_per_pixel = fb_driver.bpp / 8;

    for (uint32_t y = 0; y < fb_driver.height; y++) {
        uint8_t *row = fb_driver.virt_addr + y * fb_driver.pitch;
        for (uint32_t x = 0; x < fb_driver.width; x++) {
            uint8_t *p = row + x * bytes_per_pixel;
            p[0] = (packed >> 0) & 0xFF;
            p[1] = (packed >> 8) & 0xFF;
            p[2] = (packed >> 16) & 0xFF;
            if (bytes_per_pixel == 4) {
                p[3] = 0x00;
            }
        }
    }
}

void fb_put_pixel(uint32_t x, uint32_t y, uint32_t rgb) {
    if (!fb_driver.virt_addr) return;
    if (x >= fb_driver.width || y >= fb_driver.height) return;

    uint32_t bytes_per_pixel = fb_driver.bpp / 8;
    uint8_t *p = fb_driver.virt_addr + y * fb_driver.pitch + x * bytes_per_pixel;
    uint32_t packed = fb_pack_rgb(rgb);

    p[0] = (packed >> 0) & 0xFF;
    p[1] = (packed >> 8) & 0xFF;
    p[2] = (packed >> 16) & 0xFF;
    if (bytes_per_pixel == 4) {
        p[3] = 0x00;
    }
}

void fb_put_char_cell(int col, int row, char c, uint32_t fg_rgb, uint32_t bg_rgb) {
    if (!fb_driver.virt_addr) return;
    if (col < 0 || row < 0) return;

    uint32_t x0 = (uint32_t)col * FB_FONT_WIDTH;
    uint32_t y0 = (uint32_t)row * FB_FONT_HEIGHT;
    if (x0 + FB_FONT_WIDTH > fb_driver.width) return;
    if (y0 + FB_FONT_HEIGHT > fb_driver.height) return;

    if ((unsigned char)c < 32 || (unsigned char)c > 127) {
        c = ' ';
    }
    const uint8_t *glyph = fb_font[(unsigned char)c - 32];

    for (uint32_t y = 0; y < FB_FONT_HEIGHT; y++) {
        uint8_t bits = glyph[y];
        for (uint32_t x = 0; x < FB_FONT_WIDTH; x++) {
            // Interpret bit 0 as leftmost pixel instead of MSB.
            uint32_t rgb = (bits & (1 << x)) ? fg_rgb : bg_rgb;
            fb_put_pixel(x0 + x, y0 + y, rgb);
        }
    }
}

